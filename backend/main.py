from contextlib import asynccontextmanager
from pathlib import Path
import hashlib
import os
import secrets
import sqlite3
from urllib.parse import urlencode

from fastapi import Cookie, FastAPI, HTTPException, Response, status
from fastapi.responses import RedirectResponse
from dotenv import load_dotenv
import httpx
import psycopg
from pydantic import BaseModel, EmailStr, Field, field_validator
from pwdlib import PasswordHash

DB_PATH = Path(__file__).parent / "users.db"
load_dotenv(Path(__file__).parent / ".env")
password_hasher = PasswordHash.recommended()


def uses_postgres():
    return bool(os.getenv("DATABASE_URL"))


def profile_from_data_api(token_hash):
    url = os.getenv("SUPABASE_URL", "").rstrip("/").removesuffix("/rest/v1")
    key = os.getenv("SUPABASE_SECRET_KEY", "")
    if not url or not key:
        raise HTTPException(status_code=503, detail="Data API 설정이 완료되지 않았습니다.")
    try:
        response = httpx.post(
            f"{url}/rest/v1/rpc/current_user_profile",
            headers={"apikey": key, "Content-Profile": "app_api"},
            json={"p_token_hash": token_hash},
            timeout=10,
        )
        response.raise_for_status()
        return response.json()
    except (httpx.HTTPError, ValueError):
        raise HTTPException(status_code=503, detail="내 정보를 불러올 수 없습니다.") from None


def connect():
    if not uses_postgres():
        return sqlite3.connect(DB_PATH)
    db = psycopg.connect(os.environ["DATABASE_URL"])
    db.execute("SET search_path TO fastapi_kakao, pg_catalog")
    return db


def execute(db, statement, params=()):
    if uses_postgres():
        statement = statement.replace("?", "%s").replace("datetime('now', '+7 days')", "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC') + interval '7 days'").replace("datetime('now')", "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')")
    return db.execute(statement, params)


def init_database():
    if uses_postgres():
        with psycopg.connect(os.environ["DATABASE_URL"]) as db:
            db.execute("CREATE SCHEMA IF NOT EXISTS fastapi_kakao")
            db.execute("REVOKE ALL ON SCHEMA fastapi_kakao FROM PUBLIC")
            db.execute("SET search_path TO fastapi_kakao, pg_catalog")
            db.execute("CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at TIMESTAMP NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS kakao_accounts (kakao_id TEXT PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE REFERENCES users(id))")
    else:
        with connect() as db:
            db.execute("CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS kakao_accounts (kakao_id TEXT PRIMARY KEY, user_id INTEGER NOT NULL UNIQUE REFERENCES users(id))")


@asynccontextmanager
async def lifespan(app: FastAPI):
    init_database()
    yield


app = FastAPI(lifespan=lifespan)


class SignupRequest(BaseModel):
    name: str = Field(min_length=1, max_length=50)
    email: EmailStr
    password: str = Field(min_length=8, max_length=128)

    @field_validator("name", mode="before")
    @classmethod
    def clean_name(cls, value):
        return value.strip() if isinstance(value, str) else value


class LoginRequest(BaseModel):
    email: EmailStr
    password: str = Field(min_length=1, max_length=128)


def set_session(response, db, user_id):
    token = secrets.token_urlsafe(32)
    token_hash = hashlib.sha256(token.encode()).hexdigest()
    execute(db, "DELETE FROM sessions WHERE expires_at <= datetime('now')")
    execute(db, "INSERT INTO sessions VALUES (?, ?, datetime('now', '+7 days'))", (token_hash, user_id))
    response.set_cookie("session", token, max_age=604800, httponly=True, samesite="lax", secure=os.getenv("COOKIE_SECURE", "false").lower() == "true")


def display_user(user):
    if user["email"].endswith("@kakao.invalid"):
        user["email"] = None
    return user


@app.get("/api/auth/kakao")
def kakao_start():
    client_id = os.getenv("KAKAO_CLIENT_ID")
    if not client_id:
        raise HTTPException(status_code=503, detail="카카오 로그인이 설정되지 않았습니다.")
    state = secrets.token_urlsafe(32)
    redirect_uri = os.getenv("KAKAO_REDIRECT_URI", "http://localhost:5173/api/auth/kakao/callback")
    params = urlencode({"client_id": client_id, "redirect_uri": redirect_uri, "response_type": "code", "state": state})
    response = RedirectResponse("https://kauth.kakao.com/oauth/authorize?" + params, status_code=302)
    response.set_cookie("kakao_oauth_state", state, max_age=600, httponly=True, samesite="lax", secure=os.getenv("COOKIE_SECURE", "false").lower() == "true")
    return response


@app.get("/api/auth/kakao/callback")
def kakao_callback(code: str = "", state: str = "", kakao_oauth_state: str | None = Cookie(default=None)):
    if not state or not kakao_oauth_state or not secrets.compare_digest(state, kakao_oauth_state):
        raise HTTPException(status_code=400, detail="유효하지 않은 로그인 요청입니다.")
    if not code:
        raise HTTPException(status_code=400, detail="카카오 로그인이 취소되었습니다.")
    client_id = os.getenv("KAKAO_CLIENT_ID", "")
    if not client_id:
        raise HTTPException(status_code=503, detail="카카오 로그인이 설정되지 않았습니다.")
    data = {"grant_type": "authorization_code", "client_id": client_id, "redirect_uri": os.getenv("KAKAO_REDIRECT_URI", "http://localhost:5173/api/auth/kakao/callback"), "code": code}
    if os.getenv("KAKAO_CLIENT_SECRET"):
        data["client_secret"] = os.environ["KAKAO_CLIENT_SECRET"]
    try:
        token_response = httpx.post("https://kauth.kakao.com/oauth/token", data=data, timeout=10)
        token_response.raise_for_status()
        access_token = token_response.json()["access_token"]
        user_response = httpx.post("https://kapi.kakao.com/v2/user/me", headers={"Authorization": f"Bearer {access_token}"}, timeout=10)
        user_response.raise_for_status()
        info = user_response.json()
        kakao_id = str(int(info["id"]))
        name = (info.get("kakao_account", {}).get("profile", {}).get("nickname") or "카카오 사용자")[:50]
    except (httpx.HTTPError, KeyError, TypeError, ValueError):
        raise HTTPException(status_code=502, detail="카카오 로그인에 실패했습니다. 다시 시도해 주세요.") from None
    response = RedirectResponse(os.getenv("FRONTEND_URL", "http://localhost:5173/"), status_code=302)
    response.delete_cookie("kakao_oauth_state")
    with connect() as db:
        account = execute(db, "SELECT user_id FROM kakao_accounts WHERE kakao_id = ?", (kakao_id,)).fetchone()
        if account:
            user_id = account[0]
        else:
            email = secrets.token_hex(16) + "@kakao.invalid"
            password_hash = password_hasher.hash(secrets.token_urlsafe(32))
            user_id = execute(db, "INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?) RETURNING id", (name, email, password_hash)).fetchone()[0]
            execute(db, "INSERT INTO kakao_accounts (kakao_id, user_id) VALUES (?, ?)", (kakao_id, user_id))
        set_session(response, db, user_id)
    return response


@app.post("/api/signup", status_code=status.HTTP_201_CREATED)
def signup(user: SignupRequest):
    email = user.email.lower()
    password_hash = password_hasher.hash(user.password)
    try:
        with connect() as db:
            cursor = execute(db, "INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?) RETURNING id", (user.name, email, password_hash))
            user_id = cursor.fetchone()[0]
    except (sqlite3.IntegrityError, psycopg.errors.UniqueViolation):
        raise HTTPException(status_code=409, detail="이미 가입된 이메일입니다.")
    return {"id": user_id, "name": user.name, "email": email}


@app.post("/api/login")
def login(credentials: LoginRequest, response: Response):
    with connect() as db:
        user = execute(db, "SELECT id, name, email, password_hash FROM users WHERE email = ?", (credentials.email.lower(),)).fetchone()
        if not user or not password_hasher.verify(credentials.password, user[3]):
            raise HTTPException(status_code=401, detail="이메일 또는 비밀번호가 올바르지 않습니다.")
        set_session(response, db, user[0])
    return {"id": user[0], "name": user[1], "email": user[2]}


@app.get("/api/me")
def me(session: str | None = Cookie(default=None)):
    token_hash = hashlib.sha256((session or "").encode()).hexdigest()
    if os.getenv("SUPABASE_URL") or os.getenv("SUPABASE_SECRET_KEY"):
        user = profile_from_data_api(token_hash)
        if not user:
            raise HTTPException(status_code=401, detail="로그인이 필요합니다.")
        return display_user(user)
    with connect() as db:
        user = execute(db, "SELECT users.id, users.name, users.email FROM users JOIN sessions ON users.id = sessions.user_id WHERE sessions.token_hash = ? AND sessions.expires_at > datetime('now')", (token_hash,)).fetchone()
    if not user:
        raise HTTPException(status_code=401, detail="로그인이 필요합니다.")
    return display_user({"id": user[0], "name": user[1], "email": user[2]})


@app.post("/api/logout", status_code=204)
def logout(response: Response, session: str | None = Cookie(default=None)):
    if session:
        with connect() as db:
            execute(db, "DELETE FROM sessions WHERE token_hash = ?", (hashlib.sha256(session.encode()).hexdigest(),))
    response.delete_cookie("session")


@app.delete("/api/me", status_code=204)
def delete_account(response: Response, session: str | None = Cookie(default=None)):
    token_hash = hashlib.sha256((session or "").encode()).hexdigest()
    with connect() as db:
        user = execute(db, "SELECT user_id FROM sessions WHERE token_hash = ? AND expires_at > datetime('now')", (token_hash,)).fetchone()
        if not user:
            raise HTTPException(status_code=401, detail="로그인이 필요합니다.")
        execute(db, "DELETE FROM sessions WHERE user_id = ?", (user[0],))
        execute(db, "DELETE FROM kakao_accounts WHERE user_id = ?", (user[0],))
        execute(db, "DELETE FROM users WHERE id = ?", (user[0],))
    response.delete_cookie("session")
