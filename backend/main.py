DB_PATH = Path(__file__).parent / "users.db"
load_dotenv(Path(__file__).parent / ".env")
password_hasher = PasswordHash.recommended()


def uses_postgres():
    return bool(os.getenv("DATABASE_URL"))


def profile_from_data_api(token_hash):
    url = os.getenv("SUPABASE_URL", "").rstrip("/").removesuffix("/rest/v1")
    key = os.getenv("SUPABASE_SECRET_KEY", "")
    if not url or not key:
        raise HTTPException(status_code=503, detail="Data API 설정이 완료되지 않았습니다.")
    try:
        response = httpx.post(
            f"{url}/rest/v1/rpc/current_user_profile",
            headers={"apikey": key, "Content-Profile": "app_api"},
            json={"p_token_hash": token_hash},
            timeout=10,
        )
        response.raise_for_status()
        return response.json()
    except (httpx.HTTPError, ValueError):
        raise HTTPException(status_code=503, detail="내 정보를 불러올 수 없습니다.") from None


def connect():
    if not uses_postgres():
        db = sqlite3.connect(DB_PATH)
        db.execute("PRAGMA foreign_keys = ON")
        return db
    db = psycopg.connect(os.environ["DATABASE_URL"])
    db.execute("SET search_path TO fastapi_kakao, pg_catalog")
    return db


def execute(db, statement, params=()):
    if uses_postgres():
        statement = statement.replace("?", "%s").replace("datetime('now', '+7 days')", "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC') + interval '7 days'").replace("datetime('now')", "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')")
    return db.execute(statement, params)


def init_database():
    if uses_postgres():
        with psycopg.connect(os.environ["DATABASE_URL"]) as db:
            db.execute("CREATE SCHEMA IF NOT EXISTS fastapi_kakao")
            db.execute("REVOKE ALL ON SCHEMA fastapi_kakao FROM PUBLIC")
            db.execute("SET search_path TO fastapi_kakao, pg_catalog")
            db.execute("CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at TIMESTAMP NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS kakao_accounts (kakao_id TEXT PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE REFERENCES users(id))")
            db.execute("CREATE TABLE IF NOT EXISTS google_accounts (google_id TEXT PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE REFERENCES users(id))")
            db.execute("CREATE TABLE IF NOT EXISTS posts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, parent_id BIGINT REFERENCES posts(id) ON DELETE CASCADE, content TEXT NOT NULL, created_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS post_likes (post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, PRIMARY KEY (post_id, user_id))")
    else:
        with connect() as db:
            db.execute("CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS kakao_accounts (kakao_id TEXT PRIMARY KEY, user_id INTEGER NOT NULL UNIQUE REFERENCES users(id))")
            db.execute("CREATE TABLE IF NOT EXISTS google_accounts (google_id TEXT PRIMARY KEY, user_id INTEGER NOT NULL UNIQUE REFERENCES users(id))")
            db.execute("CREATE TABLE IF NOT EXISTS posts (id INTEGER PRIMARY KEY, author_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, parent_id INTEGER REFERENCES posts(id) ON DELETE CASCADE, content TEXT NOT NULL, created_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS post_likes (post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, PRIMARY KEY (post_id, user_id))")
    with connect() as db:
        db.execute("CREATE INDEX IF NOT EXISTS posts_parent_id_idx ON posts (parent_id, id)")
        db.execute("CREATE INDEX IF NOT EXISTS posts_author_id_idx ON posts (author_id)")
        db.execute("CREATE INDEX IF NOT EXISTS post_likes_user_id_idx ON post_likes (user_id)")


@asynccontextmanager
async def lifespan(app: FastAPI):
    init_database()
    yield


app = FastAPI(lifespan=lifespan)


class NameRequest(BaseModel):
    name: str = Field(min_length=1, max_length=50)

    @field_validator("name", mode="before")
    @classmethod
    def clean_name(cls, value):
        return value.strip() if isinstance(value, str) else value


class SignupRequest(NameRequest):
    email: EmailStr
    password: str = Field(min_length=8, max_length=128)


class LoginRequest(BaseModel):
    email: EmailStr
    password: str = Field(min_length=1, max_length=128)


class PostRequest(BaseModel):
    content: str = Field(min_length=1, max_length=500)
    parent_id: int | None = Field(default=None, gt=0)

    @field_validator("content", mode="before")
    @classmethod
    def clean_content(cls, value):
        return value.strip() if isinstance(value, str) else value


def current_user_id(session: str | None = Cookie(default=None)):
    token_hash = hashlib.sha256((session or "").encode()).hexdigest()
    with connect() as db:
        row = execute(db, "SELECT user_id FROM sessions WHERE token_hash = ? AND expires_at > datetime('now')", (token_hash,)).fetchone()
    if not row:
        raise HTTPException(status_code=401, detail="로그인이 필요합니다.")
    return row[0]


def post_rows(db, user_id, parent_id):
    condition = "p.parent_id IS NULL" if parent_id is None else "p.parent_id = ?"
    params = (user_id,) if parent_id is None else (user_id, parent_id)
    rows = execute(db, f"SELECT p.id, p.author_id, u.name, p.content, p.created_at, (SELECT COUNT(*) FROM post_likes l WHERE l.post_id = p.id), (SELECT COUNT(*) FROM posts r WHERE r.parent_id = p.id), EXISTS(SELECT 1 FROM post_likes l WHERE l.post_id = p.id AND l.user_id = ?) FROM posts p JOIN users u ON u.id = p.author_id WHERE {condition} ORDER BY p.id DESC LIMIT 100", params).fetchall()
    return [{"id": r[0], "author_id": r[1], "author": r[2], "content": r[3], "created_at": r[4], "like_count": r[5], "reply_count": r[6], "liked": bool(r[7])} for r in rows]


@app.get("/api/posts")
def list_posts(user_id: int = Depends(current_user_id)):
    with connect() as db:
        return post_rows(db, user_id, None)


@app.post("/api/posts", status_code=201)
def create_post(post: PostRequest, user_id: int = Depends(current_user_id)):
    with connect() as db:
        if post.parent_id is not None and not execute(db, "SELECT id FROM posts WHERE id = ? AND parent_id IS NULL", (post.parent_id,)).fetchone():
            raise HTTPException(status_code=404, detail="게시글을 찾을 수 없습니다.")
        row = execute(db, "INSERT INTO posts (author_id, parent_id, content, created_at) VALUES (?, ?, ?, ?) RETURNING id", (user_id, post.parent_id, post.content, datetime.now(timezone.utc).isoformat())).fetchone()
    return {"id": row[0]}


@app.get("/api/posts/{post_id}/replies")
def list_replies(post_id: int, user_id: int = Depends(current_user_id)):
    with connect() as db:
        if not execute(db, "SELECT id FROM posts WHERE id = ? AND parent_id IS NULL", (post_id,)).fetchone():
            raise HTTPException(status_code=404, detail="게시글을 찾을 수 없습니다.")
        return post_rows(db, user_id, post_id)


@app.post("/api/posts/{post_id}/like")
def toggle_like(post_id: int, user_id: int = Depends(current_user_id)):
    with connect() as db:
        if not execute(db, "SELECT id FROM posts WHERE id = ?", (post_id,)).fetchone():
            raise HTTPException(status_code=404, detail="게시글을 찾을 수 없습니다.")
        removed = execute(db, "DELETE FROM post_likes WHERE post_id = ? AND user_id = ? RETURNING post_id", (post_id, user_id)).fetchone()
        if removed:
            return {"liked": False}
        execute(db, "INSERT INTO post_likes (post_id, user_id) VALUES (?, ?) ON CONFLICT (post_id, user_id) DO NOTHING", (post_id, user_id))
        return {"liked": True}


@app.delete("/api/posts/{post_id}", status_code=204)
def delete_post(post_id: int, user_id: int = Depends(current_user_id)):
    with connect() as db:
        row = execute(db, "SELECT author_id FROM posts WHERE id = ?", (post_id,)).fetchone()
        if not row:
            raise HTTPException(status_code=404, detail="게시글을 찾을 수 없습니다.")
        if row[0] != user_id:
            raise HTTPException(status_code=403, detail="본인의 게시글만 삭제할 수 있습니다.")
        execute(db, "DELETE FROM posts WHERE id = ? AND author_id = ?", (post_id, user_id))


def set_session(response, db, user_id):
    token = secrets.token_urlsafe(32)
    token_hash = hashlib.sha256(token.encode()).hexdigest()
    execute(db, "DELETE FROM sessions WHERE expires_at <= datetime('now')")
    execute(db, "INSERT INTO sessions VALUES (?, ?, datetime('now', '+7 days'))", (token_hash, user_id))
    response.set_cookie("session", token, max_age=604800, httponly=True, samesite="lax", secure=os.getenv("COOKIE_SECURE", "false").lower() == "true")


def display_user(user):
    if user["email"].endswith(("@kakao.invalid", "@google.invalid")):
        user["email"] = None
    return user


@app.get("/api/auth/google")
def google_start():
    client_id = os.getenv("GOOGLE_CLIENT_ID")
    if not client_id or not os.getenv("GOOGLE_CLIENT_SECRET"):
        raise HTTPException(status_code=503, detail="Google 로그인이 설정되지 않았습니다.")
    state = secrets.token_urlsafe(32)
    verifier = secrets.token_urlsafe(48)
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    redirect_uri = os.getenv("GOOGLE_REDIRECT_URI", "http://localhost:5173/api/auth/google/callback")
    params = urlencode({"client_id": client_id, "redirect_uri": redirect_uri, "response_type": "code", "scope": "openid profile", "state": state, "code_challenge": challenge, "code_challenge_method": "S256"})
    response = RedirectResponse("https://accounts.google.com/o/oauth2/v2/auth?" + params, status_code=302)
    secure = os.getenv("COOKIE_SECURE", "false").lower() == "true"
    response.set_cookie("google_oauth_state", state, max_age=600, httponly=True, samesite="lax", secure=secure)
    response.set_cookie("google_oauth_verifier", verifier, max_age=600, httponly=True, samesite="lax", secure=secure)
    return response


@app.get("/api/auth/google/callback")
def google_callback(code: str = "", state: str = "", google_oauth_state: str | None = Cookie(default=None), google_oauth_verifier: str | None = Cookie(default=None)):
    if not state or not google_oauth_state or not secrets.compare_digest(state, google_oauth_state) or not google_oauth_verifier:
        raise HTTPException(status_code=400, detail="유효하지 않은 로그인 요청입니다.")
    if not code:
        raise HTTPException(status_code=400, detail="Google 로그인이 취소되었습니다.")
    client_id = os.getenv("GOOGLE_CLIENT_ID", "")
    client_secret = os.getenv("GOOGLE_CLIENT_SECRET", "")
    if not client_id or not client_secret:
        raise HTTPException(status_code=503, detail="Google 로그인이 설정되지 않았습니다.")
    data = {"grant_type": "authorization_code", "client_id": client_id, "client_secret": client_secret, "redirect_uri": os.getenv("GOOGLE_REDIRECT_URI", "http://localhost:5173/api/auth/google/callback"), "code": code, "code_verifier": google_oauth_verifier}
    try:
        token_response = httpx.post("https://oauth2.googleapis.com/token", data=data, timeout=10)
        token_response.raise_for_status()
        access_token = token_response.json()["access_token"]
        user_response = httpx.get("https://openidconnect.googleapis.com/v1/userinfo", headers={"Authorization": f"Bearer {access_token}"}, timeout=10)
        user_response.raise_for_status()
        info = user_response.json()
        google_id = info["sub"]
        if not isinstance(google_id, str) or not google_id or len(google_id) > 255:
            raise ValueError("Invalid Google ID")
        name = (info.get("name") or "Google 사용자")[:50]
    except (httpx.HTTPError, KeyError, TypeError, ValueError):
        raise HTTPException(status_code=502, detail="Google 로그인에 실패했습니다. 다시 시도해 주세요.") from None
    response = RedirectResponse(os.getenv("FRONTEND_URL", "http://localhost:5173/"), status_code=302)
    response.delete_cookie("google_oauth_state")
    response.delete_cookie("google_oauth_verifier")
    with connect() as db:
        account = execute(db, "SELECT user_id FROM google_accounts WHERE google_id = ?", (google_id,)).fetchone()
        if account:
            user_id = account[0]
        else:
            email = secrets.token_hex(16) + "@google.invalid"
            password_hash = password_hasher.hash(secrets.token_urlsafe(32))
            user_id = execute(db, "INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?) RETURNING id", (name, email, password_hash)).fetchone()[0]
            execute(db, "INSERT INTO google_accounts (google_id, user_id) VALUES (?, ?)", (google_id, user_id))
        set_session(response, db, user_id)
    return response


